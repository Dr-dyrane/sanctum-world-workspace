def build_task_packages_template() -> str:
    return '''#!/usr/bin/env python3
"""Emit prompt, grader, runbook, and prereg packages after task approval.

This file starts empty by design. Do not generate task packages until prompts,
goldens, graders, workflow names, and prereg forecasts are approved.
"""
from __future__ import annotations

import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASKFILES = ROOT / "task-files"
TASKS = {}


def emit():
    if not TASKS:
        raise SystemExit("No approved task packages configured.")
    for task, data in TASKS.items():
        out = ROOT / "tasks" / task / "current"
        out.mkdir(parents=True, exist_ok=True)
        (out / f"prompt-{data['id']}.txt").write_text(data["prompt"].rstrip() + "\\n", encoding="utf-8")
        (out / f"grader-guidelines-{data['id']}.txt").write_text(data["grader"].rstrip() + "\\n", encoding="utf-8")
        (out / "RUN-INSTRUCTIONS.md").write_text(data["run_instructions"].rstrip() + "\\n", encoding="utf-8")
        (out / f"{data['id']}-pilot-preregistration.md").write_text(data["prereg"].rstrip() + "\\n", encoding="utf-8")
        for fname in data.get("task_files", []):
            shutil.copyfile(TASKFILES / fname, out / fname)
        print("  package", data["id"])


if __name__ == "__main__":
    emit()
'''


def build_all_template(slug: str) -> str:
    return f'''#!/usr/bin/env python3
"""One-command deterministic rebuild for this world factory."""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
PY = sys.executable

STEPS = [
    ("world + supplementary files", HERE / "build_world_files.py"),
    ("task-level files", HERE / "build_task_files.py"),
    ("task goldens", HERE / "build_goldens.py"),
    ("task packages", HERE / "build_task_packages.py"),
]


def run(desc, script):
    print(f"== {{desc}}")
    r = subprocess.run([PY, str(script)], cwd=str(REPO))
    if r.returncode != 0:
        raise SystemExit(f"FAILED: {{desc}}")


def run_with_args(desc, script, *args):
    print(f"== {{desc}}")
    r = subprocess.run([PY, str(script), *args], cwd=str(REPO))
    if r.returncode != 0:
        raise SystemExit(f"FAILED: {{desc}}")


if __name__ == "__main__":
    for desc, script in STEPS:
        run(desc, script)
    run_with_args("generic world factory verification", REPO / "tools/verify/verify_world_factory.py", "worlds/{slug}")
    print("build_all complete for worlds/{slug}")
'''


def verifier_hint(slug: str) -> str:
    return f"""# Verification Notes

Run the generic factory verifier after any build:

```bash
python3 tools/verify/verify_world_factory.py worlds/{slug}
```

Before upload, also run the task-specific gate after the task package exists:

```bash
python3 tools/verify/presubmit_task_gate.py worlds/{slug}/tasks/taskN/current
```
"""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("world", help="World folder under worlds/, for example worlds/cardiorenal-respiratory-transition")
    ap.add_argument("--display-name", help="Human-readable working name")
    ap.add_argument(
        "--adopt-existing",
        action="store_true",
        help="Install the factory into an existing pre-brainstorm world folder without overwriting 00-START-HERE.md.",
    )
    args = ap.parse_args()

    world = guard_world_path(
        (REPO / args.world) if not args.world.startswith("/") else Path(args.world),
        adopt_existing=args.adopt_existing,
    )
    slug = world.name
    display = args.display_name or title_from_slug(slug)

    for d in TREE_DIRS:
        (world / d).mkdir(parents=True, exist_ok=True)
    for d in TREE_DIRS:
        write(world / d / ".gitkeep", "")

    shutil.copyfile(OV_BUILD / "epic.py", world / "build/epic.py")
    write(world / "build/README.md", build_readme(display, slug))
    write(world / "build/clinical_data.py", clinical_data_stub(display))
    write(world / "build/task_data.py", task_data_stub(display))
    write(world / "build/build_world_files.py", build_world_files_template(slug))
    write(world / "build/build_task_files.py", build_task_files_template())
    write(world / "build/build_goldens.py", build_goldens_template())
    write(world / "build/build_task_packages.py", build_task_packages_template())
    write(world / "build/build_all.py", build_all_template(slug))
    write(world / "docs/build-notes/verification.md", verifier_hint(slug))
    write(world / "00-START-HERE.md", f"""# {display} - Cockpit

Status: factory scaffold only.

This world was bootstrapped by `tools/build/bootstrap_world_factory.py`.

No clinical substrate is ratified. No DOCX, task file, golden, grader, upload, or pilot is authorized from this scaffold.

Next step: approve the world name and task architecture, then fill Phase A substrate in `build/clinical_data.py`.
""", overwrite=not args.adopt_existing)
    action = "adopted" if args.adopt_existing else "bootstrapped"
    print(f"{action} {world.relative_to(REPO)}")


if __name__ == "__main__":
    main()
