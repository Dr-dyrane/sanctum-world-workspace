def snake(slug: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", slug.lower()).strip("_")


def title_from_slug(slug: str) -> str:
    return " ".join(part.capitalize() for part in re.split(r"[-_]+", slug) if part)


def guard_world_path(path: Path, adopt_existing: bool = False) -> Path:
    path = path.resolve()
    worlds = (REPO / "worlds").resolve()
    if worlds not in path.parents:
        raise SystemExit(f"Refusing to create outside worlds/: {path}")
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]*", path.name):
        raise SystemExit("World folder name must be lowercase kebab-case.")
    if path.exists() and not adopt_existing:
        raise SystemExit(f"Refusing to overwrite existing world: {path}")
    if adopt_existing and path.exists() and not path.is_dir():
        raise SystemExit(f"Existing path is not a directory: {path}")
    return path


def write(path: Path, text: str, overwrite: bool = True) -> None:
    if path.exists() and not overwrite:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def build_readme(display: str, slug: str) -> str:
    return f"""# {display} build factory

Status: scaffold only. Clinical values are not ratified.

This folder is generated by `tools/build/bootstrap_world_factory.py` from the Ondina factory pattern.

## Canonical rule

Every DOCX for this world must render through `build_world_files.build_one()` and `epic.py`.
Do not use a bare `Document()` build for world files, task files, or goldens.

## Source modules

- `clinical_data.py` is the single source of truth for world substrate.
- `task_data.py` is the single source of truth for task-level files and package metadata.
- Every `<<PHYSICIAN: ...>>` marker must be ratified or struck before any build.

## First runnable command

This factory is intentionally not runnable until Phase A substrate is ratified and at least one file spec is authored.

When ready:

```bash
python3 worlds/{slug}/build/build_all.py
```

That command rebuilds world files, task files, goldens, packages, and runs the generic factory verifier.
"""


