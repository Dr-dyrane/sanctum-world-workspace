#!/usr/bin/env python3
"""Bootstrap a new Sanctum world from the Ondina factory pattern.

This is the canonical mechanical start for a new world. It creates the doc tree,
installs a world-local build factory, and writes placeholder source-of-truth modules.
It does not choose clinical values, build DOCX, draft goldens, or touch Studio.

Examples:
  python3 tools/build/bootstrap_world_factory.py worlds/cardiorenal-respiratory-transition --display-name "Cardiorenal Respiratory Transition"
  python3 tools/build/bootstrap_world_factory.py worlds/cardiorenal-respiratory-transition --display-name "Cardiorenal Respiratory Transition" --adopt-existing
"""
